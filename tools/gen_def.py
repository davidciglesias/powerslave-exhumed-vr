"""Generate forwarding exports for the SDL2.dll proxy.
Writes a C++ source of `#pragma comment(linker, "/EXPORT:X=SDL2_real.X")` lines; names in
OVERRIDES are instead exported from our own vp_X implementations.
usage: python -I gen_def.py <SDL2_real.dll> <out.cpp> [phase2]"""
import sys, pefile

OVERRIDES = set() if 'phase2' in sys.argv else {
    # virtual-gamepad overrides live in src/input/virtual_pad.cpp (exactly what the game imports)
    'SDL_NumJoysticks', 'SDL_IsGameController', 'SDL_GameControllerOpen', 'SDL_GameControllerClose',
    'SDL_GameControllerGetAttached', 'SDL_GameControllerGetAxis', 'SDL_GameControllerGetJoystick',
    'SDL_GameControllerGetProduct', 'SDL_GameControllerGetVendor', 'SDL_GameControllerName',
    'SDL_GameControllerHasSensor', 'SDL_GameControllerSetSensorEnabled', 'SDL_GameControllerGetSensorData',
    'SDL_JoystickGetDeviceInstanceID', 'SDL_JoystickInstanceID', 'SDL_JoystickIsHaptic',
    'SDL_HapticOpenFromJoystick', 'SDL_PollEvent',
}

pe = pefile.PE(sys.argv[1])
syms = [e for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name]
names = [e.name.decode() for e in syms]
missing = OVERRIDES - set(names)
assert not missing, missing
with open(sys.argv[2], 'w') as f:
    f.write('// generated by tools/gen_def.py - do not edit\n')
    for e in syms:
        n = e.name.decode()
        if n in OVERRIDES:
            f.write(f'#pragma comment(linker, "/EXPORT:{n}=vp_{n},@{e.ordinal}")\n')
        else:
            f.write(f'#pragma comment(linker, "/EXPORT:{n}=SDL2_real.{n},@{e.ordinal}")\n')
print(len(names), 'exports,', len(OVERRIDES), 'overridden')
